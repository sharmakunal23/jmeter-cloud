    @Nested
    @DisplayName("enableMicrometer — Actuator metric binding")
    class EnableMicrometerBehaviour {

        @Test
        @DisplayName("rejects null meter registry — fail fast at boot rather than silently producing zero metrics")
        void rejects_null_meter_registry() {
            com.perf.orchestrator.config.OrchestratorConfig cfg = realConfigForMicrometerTest();
            KafkaMetricPublisher real = KafkaMetricPublisher.create(cfg);
            try {
                assertThatThrownBy(() -> real.enableMicrometer(null))
                        .isInstanceOf(NullPointerException.class)
                        .hasMessageContaining("meterRegistry");
            } finally {
                real.close();
            }
        }

        @Test
        @DisplayName("attaching a real MicrometerProducerListener to the factory does not throw — wiring is type-correct")
        void wiring_is_type_correct() {
            com.perf.orchestrator.config.OrchestratorConfig cfg = realConfigForMicrometerTest();
            KafkaMetricPublisher real = KafkaMetricPublisher.create(cfg);
            try {
                io.micrometer.core.instrument.simple.SimpleMeterRegistry registry =
                        new io.micrometer.core.instrument.simple.SimpleMeterRegistry();
                org.assertj.core.api.Assertions.assertThatCode(() -> real.enableMicrometer(registry))
                        .as("MicrometerProducerListener type parameters must align with " +
                            "DefaultKafkaProducerFactory.addListener — pre-K-1 regression guard")
                        .doesNotThrowAnyException();
            } finally {
                real.close();
            }
        }

        @Test
        @DisplayName("rejects enableMicrometer on a test-constructed publisher (null producerFactory)")
        void rejects_when_no_producer_factory() {
            io.micrometer.core.instrument.simple.SimpleMeterRegistry registry =
                    new io.micrometer.core.instrument.simple.SimpleMeterRegistry();
            assertThatThrownBy(() -> publisher.enableMicrometer(registry))
                    .isInstanceOf(IllegalStateException.class)
                    .hasMessageContaining("create(config)");
        }

        /** Minimal valid config that {@link KafkaMetricPublisher#create(com.perf.orchestrator.config.OrchestratorConfig) create()} can build a producer factory from. */
        private static com.perf.orchestrator.config.OrchestratorConfig realConfigForMicrometerTest() {
            java.util.Map<String, String> env = new java.util.HashMap<>();
            env.put("POD_NAME", "jmeter-test-pod");
            env.put("TEST_REGION", "us-east-1");
            env.put("RUN_ID", "test-run-id");
            env.put("JTL_PATH", "/results/results.jtl");
            env.put("SENTINEL_PATH", "/results/.done");
            env.put("KAFKA_BROKERS", "localhost:9092");
            env.put("SCHEMA_REGISTRY_URL", "http://localhost:8081");
            env.put("KAFKA_TOPIC", "jmeter.metrics.perSecond");
            return com.perf.orchestrator.config.OrchestratorConfig.from(env);
        }
    }

    // -----------------------------------------------------------------------
    // Close behaviour — JVM shutdown only
    // -----------------------------------------------------------------------

    @Nested
    @DisplayName("close — JVM shutdown")
    class CloseAndFlush {

        @Test
        @DisplayName("close() flushes pending envelopes before disposing — published count reflects them")
        void close_flushes_before_disposing() {
            MockProducer<String, WorkerMetricBatch> lazyProducer = newMockProducer(false);
            KafkaMetricPublisher lazyPublisher = new KafkaMetricPublisher(
                    null, templateFor(lazyProducer), MetricKeyStrategy.standard());

            lazyPublisher.publishBatch(envelope(LABEL), TOPIC);
            assertThat(lazyProducer.history()).hasSize(1);

            lazyPublisher.close();

            assertThat(lazyPublisher.getPublishedCount())
                    .as("flush() inside close() must trigger delivery callbacks for all queued envelopes")
                    .isEqualTo(1L);
        }

        @Test
        @DisplayName("second close() call is a no-op — does not throw IllegalStateException")
        void double_close_is_safe() {
            publisher.close();

            org.assertj.core.api.Assertions.assertThatCode(publisher::close)
                    .doesNotThrowAnyException();
        }
    }
