    @Nested
    @DisplayName("publishAll")
    class PublishAll {

        @Test
        @DisplayName("sends one Kafka record per envelope in the list")
        void sends_one_record_per_envelope() {
            List<WorkerMetricBatch> envelopes = List.of(
                    envelope("POST /api/payment"),
                    envelope("GET /api/account"),
                    envelope("DELETE /api/session")
            );

            publisher.publishAll(envelopes, TOPIC);

            assertThat(mockProducer.history()).hasSize(3);
        }

        @Test
        @DisplayName("each record carries its envelope's first entry's label — proves order preserved")
        void each_record_carries_its_envelope() {
            List<WorkerMetricBatch> envelopes = List.of(
                    envelope("POST /api/payment"),
                    envelope("GET /api/account")
            );

            publisher.publishAll(envelopes, TOPIC);

            List<String> firstEntryLabels = mockProducer.history().stream()
                    .map(ProducerRecord::value)
                    .map(b -> b.getEntries().get(0).getLabel().toString())
                    .toList();

            assertThat(firstEntryLabels).containsExactlyInAnyOrder("POST /api/payment", "GET /api/account");
        }

        @Test
        @DisplayName("is a no-op for an empty list — does not send to Kafka at all")
        void empty_list_sends_nothing() {
            publisher.publishAll(List.of(), TOPIC);

            assertThat(mockProducer.history()).isEmpty();
        }

        @Test
        @DisplayName("rejects null list")
        void rejects_null_list() {
            assertThatThrownBy(() -> publisher.publishAll(null, TOPIC))
                    .isInstanceOf(NullPointerException.class);
        }
    }

