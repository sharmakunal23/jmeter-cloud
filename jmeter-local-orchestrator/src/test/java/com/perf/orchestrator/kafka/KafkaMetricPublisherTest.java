    @Nested
    @DisplayName("delivery failure handling")
    class DeliveryFailureHandling {

        @Test
        @DisplayName("failed count increments when the broker rejects an envelope")
        void failed_count_increments_on_rejection() {
            // autoComplete=false: we control when sends complete
            MockProducer<String, WorkerMetricBatch> failingProducer = newMockProducer(false);
            KafkaMetricPublisher failingPublisher = new KafkaMetricPublisher(
                    null, templateFor(failingProducer), MetricKeyStrategy.standard());

            failingPublisher.publishBatch(envelope(LABEL), TOPIC);

            failingProducer.errorNext(new RuntimeException("broker unavailable"));

            assertThat(failingPublisher.getFailedCount()).isEqualTo(1L);
        }
    }

    // -----------------------------------------------------------------------
    // Per-run flush behaviour
    // -----------------------------------------------------------------------

    @Nested
    @DisplayName("flush — per-run end-of-stream")
    class FlushBehaviour {

        @Test
        @DisplayName("flush() drives MockProducer's pending queue — published count reflects flushed envelopes")
        void flush_drains_pending_records() {
            MockProducer<String, WorkerMetricBatch> lazyProducer = newMockProducer(false);
            KafkaMetricPublisher lazyPublisher = new KafkaMetricPublisher(
                    null, templateFor(lazyProducer), MetricKeyStrategy.standard());

            lazyPublisher.publishBatch(envelope("POST /api/payment"), TOPIC);
            lazyPublisher.publishBatch(envelope("GET /api/account"), TOPIC);

            assertThat(lazyProducer.history()).hasSize(2);
            assertThat(lazyPublisher.getPublishedCount()).isZero();

            lazyPublisher.flush();

            assertThat(lazyPublisher.getPublishedCount())
                    .as("flush() must trigger the delivery callbacks for all queued envelopes")
                    .isEqualTo(2L);
        }

        @Test
        @DisplayName("flush() on a closed publisher is a no-op — does not throw IllegalStateException")
        void flush_after_close_is_safe() {
            publisher.close();

            org.assertj.core.api.Assertions.assertThatCode(publisher::flush)
                    .doesNotThrowAnyException();
        }
    }

    // -----------------------------------------------------------------------
    // Micrometer wiring
